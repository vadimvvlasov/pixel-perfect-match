export const formatDate = (d: string, short = false) =>
  new Intl.DateTimeFormat("ru-RU", {
    day: "numeric",
    month: short ? "short" : "long",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(`${d}T12:00:00Z`));
export const formatRange = (s: string, e: string) =>
  s === e ? formatDate(s, true) : `${formatDate(s, true)} – ${formatDate(e, true)}`;
export const formatArea = (a: number) =>
  `${new Intl.NumberFormat("ru-RU", { maximumFractionDigits: 1 }).format(a)}\u00a0${ru.hectare}`;
export function jobMessage(message: string | null) {
  if (!message) return "";
  return (
    ru.message[message as keyof typeof ru.message] ??
    message.replace(/(\d+) fields/, `$1 ${ru.fields}`)
  );
}
